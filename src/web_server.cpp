static void handleStatus() {
    static char buf[2200];
    char *p = buf;
    size_t left = sizeof(buf);

    const CameraTelemetry &tel = camGetTelemetry();
    const FcTelemetry &fc = fcGetTelemetry();
    const OpenSlateSettings &cfg = settingsGet();

    BleConnectionState st = camGetState();
    static const char *kStateNames[] =
        {"OFF", "SCANNING", "CONNECTING", "PAIRING", "CONNECTED"};

    int batt = tel.batteryPercent <= 100 ? tel.batteryPercent : -1;

    // Saved-camera registry with live status of the active entry.
    char cams[512];
    {
        size_t o = 0;
        o += snprintf(cams + o, sizeof(cams) - o, "[");
        for (uint8_t i = 0; i < cfg.camCount; i++) {
            const SavedCamera &c = cfg.cams[i];
            const char *nm = c.name[0] ? c.name : c.mac;
            char safeName[sizeof(c.name)];
            jsonEscape(nm, safeName, sizeof(safeName));
            o += snprintf(cams + o, sizeof(cams) - o,
                          "%s{\"t\":%u,\"n\":\"%s\",\"m\":\"%s\",\"g\":\"%s\",\"a\":%s,\"on\":%s}",
                          i ? "," : "", c.type, safeName, c.mac, c.tag,
                          c.active ? "true" : "false",
                          camSavedIsReady(i) ? "true" : "false");
            if (o >= sizeof(cams) - 8) break;
        }
        if (o < sizeof(cams) - 1) snprintf(cams + o, sizeof(cams) - o, "]");
        else strlcpy(cams, "[]", sizeof(cams));   // never emit cut-off JSON
    }

    // Pending cams discovered in current scan (drained from BLE host task by
    // loop()). Exposed so the UI can show in-progress discoveries before they
    // land in the persisted registry. Cheap: no allocation, just strlcpy.
    // Sorted by RSSI descending (strongest first) and capped at 10 entries.
    char pending[640] = "[]";
    {
        ScanResult const *sorted[MAX_SCAN_RESULTS];
        uint8_t n = scanResultsGetSortedByRssi(sorted, MAX_SCAN_RESULTS);
        size_t o = 0;
        o += snprintf(pending + o, sizeof(pending) - o, "[");
        for (uint8_t i = 0; i < n && o < sizeof(pending) - 80; i++) {
            const char *typeStr = (sorted[i]->type == CAMERA_GOPRO) ? "GoPro" : "DJI";
            // Any nearby advertiser can land here: escape its name.
            char safeName[sizeof(sorted[i]->name)];
            jsonEscape(sorted[i]->name, safeName, sizeof(safeName));
            o += snprintf(pending + o, sizeof(pending) - o,
                "%s{\"mac\":\"%s\",\"n\":\"%s\",\"t\":\"%s\",\"r\":%d}",
                i ? "," : "", sorted[i]->mac, safeName, typeStr, sorted[i]->rssi);
        }
        if (o < sizeof(pending) - 1) snprintf(pending + o, sizeof(pending) - o, "]");
        else strlcpy(pending, "[]", sizeof(pending));
    }

    // Last connect-attempt error from the active backend (empty = no error).
    // The Web UI shows it as a toast and clears the field on next success.
    const char *lastErr = camGetLastError();
    char safeErr[64] = "";
    {
        size_t i = 0;
        for (; lastErr[i] && i < sizeof(safeErr) - 1; i++) {
            char ch = lastErr[i];
            safeErr[i] = (ch == '"' || ch == '\\') ? ' ' : ch;
        }
        safeErr[i] = '\0';
    }

    // heap at top level so the UI can show/monitor it. The sys.heap field
    // is kept for backward compatibility.
    uint32_t heap = ESP.getFreeHeap();
    const CpuStats &cpu = cpuStatsGet();

    // S09: escape FC-provided strings before embedding them in JSON.
    char escOsd[4][OSD_MAX_TEXT_LEN + 1];
    char escApi[16], escFw[16], escBoard[32];
    for (int i = 0; i < 4; i++) jsonEscape(osdSlotText(i), escOsd[i], sizeof(escOsd[i]));
    jsonEscape(fcApiVersion(), escApi, sizeof(escApi));
    jsonEscape(fcFirmwareVersion(), escFw, sizeof(escFw));
    jsonEscape(fcBoardName(), escBoard, sizeof(escBoard));

    size_t w = snprintf(p, left,
        "{\"heap\":%u,"
        "\"connectedCams\":%u,"
        "\"cam\":{\"type\":%d,\"name\":\"%s\",\"state\":%d,"
        "\"stateName\":\"%s\",\"batt\":%d,\"battMv\":%u,\"battTemp\":%d,"
        "\"recTime\":%u,\"valid\":%s,"
        "\"model\":\"%s\"},"
        "\"rec\":{\"desired\":%s,\"switchOn\":%s,\"roa\":%s,\"sod\":%s,\"rcValue\":%u,"
        "\"auxCh\":%u,\"thr\":%u,\"deb\":%u},"
        "\"slots\":[%d,%d,%d,%d],"
        "\"osd\":[\"%s\",\"%s\",\"%s\",\"%s\"],"
        "\"wifiSwitch\":%d,\"wifiOn\":%s,\"apOffArmed\":%s,\"scanAll\":%s,"
        "\"lastError\":\"%s\","
        "\"cams\":%s,\"pending_cams\":%s,\"scanning\":%s,"
        "\"fc\":{\"alive\":%s,\"armed\":%s,\"vbat10\":%u,\"rssi\":%u,"
        "\"cycle\":%u,\"api\":\"%s\",\"fw\":\"%s\",\"board\":\"%s\"},"
        "\"sys\":{\"heap\":%u,\"uptime\":%lu,\"ip\":\"%s\",\"sta\":%d,"
        "\"cpu\":%u,\"cpuLoop\":%u,\"version\":\"%s\"}}",
        heap,
        (unsigned)camConnectedCount(),
        (int)cfg.camera, camGetName(), (int)st, kStateNames[st], batt,
        (unsigned)tel.batteryMv,
        tel.batteryTempC10 == INT16_MIN ? -9999 : (int)tel.batteryTempC10,
        tel.recTimeSeconds, tel.dataValid ? "true" : "false", tel.model,
        recorderDesiredRecording() ? "true" : "false",
        recorderSwitchOn() ? "true" : "false",
        cfg.recordOnArm ? "true" : "false",
        cfg.stopOnDisarm ? "true" : "false",
        recorderLastRcValue(),
        cfg.auxChannelIndex, cfg.rcThresholdUs, cfg.debounceMs,
        cfg.osdSlot[0], cfg.osdSlot[1], cfg.osdSlot[2], cfg.osdSlot[3],
        escOsd[0], escOsd[1], escOsd[2], escOsd[3],
        (cfg.wifiSwitchCh <= 15) ? (int)cfg.wifiSwitchCh : -1,
        _up ? "true" : "false",
        cfg.apOffArmed ? "true" : "false",
        cfg.scanAll ? "true" : "false",
        safeErr,
        cams, pending,
        scanResultsIsScanning() ? "true" : "false",
        fc.fcAlive ? "true" : "false", fc.armed ? "true" : "false",
        fc.vbat10, fc.rssi / 10, fc.cycleTimeUs,
        escApi, escFw, escBoard,
        heap, millis() / 1000UL, _ipStr,
        WiFi.softAPgetStationNum(),
        (unsigned)cpu.total, (unsigned)cpu.loopTask,
        FIRMWARE_VERSION);
    if (w >= left) {
        // Buffer exhausted — fail closed with a minimal valid payload rather
        // than sending truncated JSON that breaks the UI parser.
        snprintf(buf, sizeof(buf),
                 "{\"ok\":false,\"error\":\"status truncated\"}");
    }

    _server.sendHeader("Cache-Control", "no-store");
    _server.sendHeader("X-Content-Type-Options", "nosniff");
    _server.send(200, "application/json", buf);
}

static void sendJsonError(const char *msg) {
    char buf[128];
    snprintf(buf, sizeof(buf), "{\"ok\":false,\"error\":\"%s\"}", msg);
    _server.send(400, "application/json", buf);
}

static void sendArmedError() {
    _server.send(409, "application/json",
                 "{\"ok\":false,\"error\":\"not allowed while FC is armed\"}");
}

static void handleSettingsPost() {
    String body = _server.arg("plain");
    if (!requireSaneBody(body)) return;

    if (!jsonHas(body, "camera") && !jsonHas(body, "auxChannel") &&
        !jsonHas(body, "recordOnArm") && !jsonHas(body, "ssid") &&
        !jsonHas(body, "slot0") && !jsonHas(body, "slot1") &&
        !jsonHas(body, "slot2") && !jsonHas(body, "slot3") &&
        !jsonHas(body, "wifiSwitch") && !jsonHas(body, "scanAll") &&
        !jsonHas(body, "apOffArmed") &&
        !jsonHas(body, "threshold") && !jsonHas(body, "debounce") &&
        !jsonHas(body, "stopOnDisarm")) {
        sendJsonError("no recognized keys");
        return;
    }

    // ── Phase 1: validate EVERY provided field before mutating anything ──
    // A later invalid field must not leave earlier (persisted) changes
    // behind, so all checks run first and the settings struct is only
    // touched once every value is known good.
    bool   haveCamera = jsonHas(body, "camera");
    long   camVal     = jsonGetNum(body, "camera", -1);
    bool   haveAux    = jsonHas(body, "auxChannel");
    long   auxVal     = jsonGetNum(body, "auxChannel", -1);
    bool   haveThr    = jsonHas(body, "threshold");
    long   thrVal     = jsonGetNum(body, "threshold", -1);
    bool   haveDeb    = jsonHas(body, "debounce");
    long   debVal     = jsonGetNum(body, "debounce", -1);
    bool   haveWifi   = jsonHas(body, "wifiSwitch");
    long   wifiVal    = jsonGetNum(body, "wifiSwitch", -1);
    bool   haveSsid   = jsonHas(body, "ssid");
    String ssid       = haveSsid ? jsonGetStr(body, "ssid") : String();
    bool   havePass   = jsonHas(body, "pass");
    String pass       = havePass ? jsonGetStr(body, "pass") : String();
    bool   haveSlot[4];
    long   slotVal[4];
    if (haveSsid) ssid.trim();
    if (havePass) pass.trim();

    for (uint8_t s = 0; s < 4; s++) {
        char key[8];
        snprintf(key, sizeof(key), "slot%d", s);
        haveSlot[s] = jsonHas(body, key);
        slotVal[s]  = jsonGetNum(body, key, -1);
    }

    if (haveCamera && camVal != CAMERA_DJI && camVal != CAMERA_GOPRO) {
        sendJsonError("invalid camera type");
        return;
    }
    if (haveAux && (auxVal < 0 || auxVal > 15)) {
        sendJsonError("channel out of range");
        return;
    }
    if (haveThr && (thrVal < 1200 || thrVal > 1800)) {
        sendJsonError("threshold out of range");
        return;
    }
    if (haveDeb && (debVal < 50 || debVal > 1000)) {
        sendJsonError("debounce out of range");
        return;
    }
    for (uint8_t s = 0; s < 4; s++) {
        if (haveSlot[s] && (slotVal[s] < 0 || slotVal[s] >= OSD_SLOT_COUNT)) {
            sendJsonError("invalid slot content");
            return;
        }
    }
    if (haveWifi && !((wifiVal >= 0 && wifiVal <= 15) || wifiVal == -1)) {
        sendJsonError("wifi switch channel out of range");
        return;
    }
    if (haveSsid && (ssid.length() < 1 || ssid.length() > WIFI_AP_SSID_MAX_LEN)) {
        sendJsonError("SSID must be 1-32 chars");
        return;
    }
    if (havePass && (pass.length() < WIFI_AP_PASS_MIN_LEN ||
                     pass.length() > WIFI_AP_PASS_MAX_LEN)) {
        // WPA2-PSK is 8..63 chars. Empty (open AP) is rejected on POST —
        // use the serial console for recovery instead of one-click de-auth.
        sendJsonError("password must be 8-63 chars");
        return;
    }

    // Flight safety: brand switch tears down the camera links, credential
    // changes restart the AP — neither may happen while armed.
    if (fcIsArmed() &&
        ((haveCamera && settingsGet().camera != (CameraType)camVal) ||
         haveSsid || havePass)) {
        sendArmedError();
        return;
    }

    // ── Phase 2: all values valid — apply and persist ──────────────────
    OpenSlateSettings &cfg = settingsGet();
    bool apNeedsRestart = false;

    // Camera brand
    if (haveCamera && cfg.camera != (CameraType)camVal) {
        camSetCamera((CameraType)camVal);   // Also persists settings
    }

    // Record switch
    if (haveAux)  cfg.auxChannelIndex = (uint8_t)auxVal;
    if (haveThr)  cfg.rcThresholdUs   = (uint16_t)thrVal;
    if (haveDeb)  cfg.debounceMs      = (uint16_t)debVal;

    // Behaviour toggles
    if (jsonHas(body, "recordOnArm"))
        cfg.recordOnArm = jsonGetBool(body, "recordOnArm");
    if (jsonHas(body, "stopOnDisarm"))
        cfg.stopOnDisarm = jsonGetBool(body, "stopOnDisarm");

    // "Show all nearby devices" toggle (NVS-persisted, no AP restart).
    if (jsonHas(body, "scanAll"))
        cfg.scanAll = jsonGetBool(body, "scanAll");

    // Hotspot off while armed (applied by wifiSwitchUpdate()).
    if (jsonHas(body, "apOffArmed"))
        cfg.apOffArmed = jsonGetBool(body, "apOffArmed");

    // Wi-Fi radio switch channel (-1 or 255 = disabled)
    if (haveWifi) cfg.wifiSwitchCh = (wifiVal == -1) ? 255 : (uint8_t)wifiVal;

    // OSD slots
    for (uint8_t s = 0; s < 4; s++) {
        if (haveSlot[s]) cfg.osdSlot[s] = (uint8_t)slotVal[s];
    }

    // Wi-Fi credentials
    if (haveSsid) {
        strlcpy(cfg.apSsid, ssid.c_str(), sizeof(cfg.apSsid));
        apNeedsRestart = true;
    }
    if (havePass) {
        strlcpy(cfg.apPass, pass.c_str(), sizeof(cfg.apPass));
        apNeedsRestart = true;
    }

    settingsSave();
    DBG("WEB: settings saved");

    if (apNeedsRestart) {
        _server.send(200, "application/json",
                     "{\"ok\":true,\"apRestart\":true}");
        // P01: restart from webUpdate() once the response had time to flush.
        scheduleDeferred(WEB_DEFER_AP_RESTART);
        return;
    }

    _server.send(200, "application/json", "{\"ok\":true}");
}

static void handleCommand() {
    String body = _server.arg("plain");
    if (!requireSaneBody(body)) return;
    String cmd = jsonGetStr(body, "cmd");

    if (cmd == "start") {
        recorderManualStart();
        _server.send(200, "application/json", "{\"ok\":true}");
    } else if (cmd == "stop") {
        recorderManualStop();
        _server.send(200, "application/json", "{\"ok\":true}");
    } else if (cmd == "reboot") {
        if (fcIsArmed()) { sendArmedError(); return; }
        _server.send(200, "application/json", "{\"ok\":true}");
        scheduleDeferred(WEB_DEFER_REBOOT);   // P01: no delay() in the handler
    } else {
        sendJsonError("unknown command");
    }
}

// ──────────────────────────────────────────────────────────────────────────────
// Saved-camera registry endpoints:  POST /api/camera {"select":i} | {"remove":i}
// ──────────────────────────────────────────────────────────────────────────────

static void handleCameraPost() {
    String body = _server.arg("plain");
    if (!requireSaneBody(body)) return;

    // {"label":i,"text":"STK"} — short OSD label. Touches no radio link, so
    // it is allowed while armed. Normalised to A-Z/0-9, max 4 characters.
    if (jsonHas(body, "label")) {
        long idx = jsonGetNum(body, "label", -1);
        String text = jsonGetStr(body, "text");
        if (idx < 0 || idx >= MAX_SAVED_CAMERAS ||
            !camRegistrySetTag((uint8_t)idx, text.c_str())) {
            sendJsonError("invalid camera index");
            return;
        }
        char out[48];
        snprintf(out, sizeof(out), "{\"ok\":true,\"tag\":\"%s\"}",
                 settingsGet().cams[(uint8_t)idx].tag);
        _server.send(200, "application/json", out);
        return;
    }

    // Flight safety: scans, pairing and slot changes disturb the live camera
    // links (shared radio, reconnects) — refuse them while armed.
    if (fcIsArmed()) { sendArmedError(); return; }

    if (jsonHas(body, "scan")) {
        // {"scan": true} — user-initiated discovery scan.
        // Refuse to start a second scan while one is in progress so the
        // 5 s window is not split across two competing jobs on the radio.
        if (scanResultsIsScanning()) {
            // Graceful degradation: tell the UI we are already scanning,
            // don't throw 400.
            _server.send(200, "application/json", "{\"ok\":true,\"already\":true}");
            return;
        }
        // Server-side throttle: block scripted scan floods that would hog
        // the single 2.4 GHz radio (BLE scan duty + SoftAP beacons).
        uint32_t now = millis();
        if (_lastScanStartMs != 0 && now - _lastScanStartMs < WEB_SCAN_COOLDOWN_MS) {
            _server.send(429, "application/json",
                         "{\"ok\":false,\"error\":\"scan cooldown, try again shortly\"}");
            return;
        }
        if (!camRequestUserScan()) {
            _server.send(409, "application/json",
                         "{\"ok\":false,\"error\":\"BLE busy, try again shortly\"}");
            return;
        }
        _lastScanStartMs = now;
        _server.send(200, "application/json", "{\"ok\":true}");
    } else if (jsonHas(body, "select")) {
        long idx = jsonGetNum(body, "select", -1);
        if (idx < 0 || !camRegistrySelect((uint8_t)idx)) {
            sendJsonError("invalid camera index");
            return;
        }
        camKick();   // Stop scanning, connect to the selected MAC right away
        _server.send(200, "application/json", "{\"ok\":true}");
    } else if (jsonHas(body, "remove")) {
        long idx = jsonGetNum(body, "remove", -1);
        // Remember whether the removed entry was the ACTIVE camera BEFORE
        // removal — camRegistryRemove() may set a new active fallback.
        bool wasActive = (idx >= 0 && idx < MAX_SAVED_CAMERAS) &&
                         settingsGet().cams[(uint8_t)idx].active;
        if (idx < 0 || idx >= MAX_SAVED_CAMERAS ||
            !camRegistryRemove((uint8_t)idx)) {
            sendJsonError("invalid camera index");
            return;
        }
        // Only touch the link if the removed camera was the connected one —
        // dropping it when removing an inactive entry would unpair the
        // camera that is still active. With a remaining registry entry the
        // registry has already activated a fallback: re-target it (also
        // disconnects the old link). Only when the registry is empty do we
        // fully disconnect (camDisconnect() then has no active flag to wipe).
        if (wasActive) {
            if (settingsGet().camCount > 0) camKick();
            else camDisconnect();
        }
        _server.send(200, "application/json", "{\"ok\":true}");
    } else if (jsonHas(body, "pair")) {
        // "pair" body: {"mac":"AA:BB:...","type":0|1}
        String mac = jsonGetStr(body, "mac");
        long type = jsonGetNum(body, "type", -1);
        
        // Security: Validate MAC format strictly (17 chars, XX:XX:XX:XX:XX:XX)
        if (mac.length() != 17) {
            sendJsonError("pair: invalid MAC length");
            return;
        }
        for (int i = 0; i < 17; i++) {
            char c = mac.charAt(i);
            if (i % 3 == 2) {
                if (c != ':') {
                    sendJsonError("pair: invalid MAC format");
                    return;
                }
            } else {
                if (!isHexadecimalDigit(c)) {
                    sendJsonError("pair: invalid MAC character");
                    return;
                }
            }
        }
        
        if ((type != CAMERA_DJI && type != CAMERA_GOPRO)) {
            sendJsonError("pair: mac and type required");
            return;
        }
        
        // Check if device is currently visible in scan results (online check).
        // Uses the same live scan-results table that /api/scan serves, so a
        // device shown in the Discover card is always pairable.
        ScanResult const *sorted[MAX_SCAN_RESULTS];
        uint8_t scount = scanResultsGetSortedByRssi(sorted, MAX_SCAN_RESULTS);
        bool isOnline = false;
        char nameBuf[24] = "";
        for (uint8_t i = 0; i < scount; i++) {
            if (strcasecmp(sorted[i]->mac, mac.c_str()) == 0 &&
                sorted[i]->type == (uint8_t)type) {
                isOnline = true;
                // Sanitize device name to prevent XSS
                sanitizeDeviceName(nameBuf, sorted[i]->name, sizeof(nameBuf));
                break;
            }
        }
        // Don't allow pairing with offline devices
        if (!isOnline) {
            sendJsonError("Cannot pair: device is offline or not in range");
            return;
        }
        if (!camRegistrySave((uint8_t)type, mac.c_str(),
                              nameBuf[0] ? nameBuf : mac.c_str())) {
            sendJsonError("pair: registry full or invalid");
            return;
        }
        // Find the newly-saved entry's index and select+kick it.
        for (uint8_t i = 0; i < settingsGet().camCount; i++) {
            if (strcasecmp(settingsGet().cams[i].mac, mac.c_str()) == 0 &&
                settingsGet().cams[i].type == (uint8_t)type) {
                camRegistrySelect(i);
                camKick();
                break;
            }
        }
        _server.send(200, "application/json", "{\"ok\":true}");
    } else {
        sendJsonError("expected scan, select, remove, or pair");
    }
}

// MSP passthrough — lets the Web UI talk MSP directly to the FC.
// Read-only allowlist: safe introspection commands only.  This is the
// foundation for a future browser-side "configurator-lite" panel.
//
// PRIVACY NOTE: MSP_RAW_GPS (108) is deliberately NOT exposed — GPS/position
// over unauthenticated Wi-Fi is a tracking risk. Altitude (109) stays because
// the Dashboard MSP console offers it and it carries no position fix.
// ──────────────────────────────────────────────────────────────────────────────

// Named MSP codes used by the allowlist (see msp_protocol.h for the rest).
static const uint16_t kMspBuildInfo    = 5;
static const uint16_t kMspMotor        = 104;
static const uint16_t kMspAltitude     = 109;
static const uint16_t kMspBoxNames     = 116;
static const uint16_t kMspBatteryState = 130;

static bool mspCmdAllowed(uint16_t cmd) {
    static const uint16_t kAllowed[] = {
        MSP_API_VERSION,   // 1
        MSP_FC_VARIANT,    // 2
        MSP_FC_VERSION,    // 3
        MSP_BOARD_INFO,    // 4
        kMspBuildInfo,     // 5
        MSP_STATUS,        // 101
        kMspMotor,         // 104
        MSP_RC,            // 105
        kMspAltitude,      // 109 (no GPS: see note above)
        MSP_ANALOG,        // 110
        kMspBoxNames,      // 116
        MSP_BOXIDS,        // 119
        kMspBatteryState,  // 130
    };
    for (size_t i = 0; i < sizeof(kAllowed) / sizeof(kAllowed[0]); i++) {
        if (kAllowed[i] == cmd) return true;
    }
    return false;
}

static void handleMspPost() {
    String body = _server.arg("plain");
    if (!requireSaneBody(body)) return;
    long cmd = jsonGetNum(body, "cmd", -1);

    if (cmd < 0 || cmd > 255) {
        sendJsonError("missing/invalid cmd");
        return;
    }
    if (!mspCmdAllowed((uint16_t)cmd)) {
        sendJsonError("command not in read-only allowlist");
        return;
    }
    // The wait below holds loop() for up to MSP_RESPONSE_TIMEOUT_MS: never
    // in flight, where record switch and OSD must stay responsive.
    if (fcIsArmed()) { sendArmedError(); return; }

    // Hand already-buffered frames to the FC status parser instead of
    // throwing them away (that used to drop arm/status updates).
    {
        MspMessage stale{};
        while (Serial1.available()) {
            if (mspParseByte((uint8_t)Serial1.read(), stale)) fcStatusFeed(stale);
        }
    }

    mspSendRequest((uint8_t)cmd);

    MspMessage msg{};  // E13: zero-init (no backing for uninit)
    uint32_t started = millis();
    bool got = false;
    while (millis() - started < MSP_RESPONSE_TIMEOUT_MS) {
        while (Serial1.available()) {
            uint8_t b = Serial1.read();
            if (mspParseByte(b, msg)) {
                fcStatusFeed(msg);          // Keep live stats fresh
                if ((uint16_t)msg.cmd == (uint16_t)cmd && msg.valid && !msg.isError) {
                    got = true;
                    break;
                }
            }
        }
        if (got) break;
        delay(2);
        yield();
    }

    if (!got) {
        _server.send(504, "application/json",
                     "{\"ok\":false,\"error\":\"FC timeout\"}");
        return;
    }

    // Hex-encode the payload.
    static char hex[MSP_MAX_PAYLOAD_SIZE * 3 + 4];
    size_t o = 0;
    for (uint8_t i = 0; i < msg.payloadSize; i++) {
        o += snprintf(hex + o, sizeof(hex) - o, "%02X", msg.payload[i]);
    }
    hex[o] = '\0';

    char out[192];
    snprintf(out, sizeof(out),
             "{\"ok\":true,\"cmd\":%u,\"len\":%u,\"payload\":\"%s\"}",
             (unsigned)msg.cmd, (unsigned)msg.payloadSize, hex);
    _server.send(200, "application/json", out);
}

// ──────────────────────────────────────────────────────────────────────────────
// Scan Results Endpoint
// ──────────────────────────────────────────────────────────────────────────────

static void handleScanResults() {
    // Serve the REAL scan-results table (populated directly by the BLE
    // scan callbacks, sorted strongest-RSSI first) — not the cam_registry
    // discovered list, which is fed through a single-slot "newest wins"
    // funnel and drops all but the last advertiser.
    ScanResult const *sorted[MAX_SCAN_RESULTS];
    uint8_t n = scanResultsGetSortedByRssi(sorted, MAX_SCAN_RESULTS);

    static char buf[4096];
    char *p = buf;
    size_t left = sizeof(buf);

    size_t w = snprintf(p, left, "{\"scanning\":%s,\"results\":[",
                        scanResultsIsScanning() ? "true" : "false");
    p += w; left -= w;

    // Field names match what the Web UI's renderDiscovered() reads:
    // r.mac, r.n (name), r.t (type STRING 'GoPro'/'DJI'), r.rssi.
    for (uint8_t i = 0; i < n && left > 96; i++) {
        if (i > 0) { *p++ = ','; left--; }

        // Sanitize device name before sending to client (prevent XSS)
        char sanitizedName[24] = "";
        sanitizeDeviceName(sanitizedName, sorted[i]->name, sizeof(sanitizedName));

        const char *typeStr = (sorted[i]->type == CAMERA_GOPRO) ? "GoPro" : "DJI";
        w = snprintf(p, left,
                     "{\"mac\":\"%s\",\"n\":\"%s\",\"t\":\"%s\",\"rssi\":%d}",
                     sorted[i]->mac, sanitizedName, typeStr, sorted[i]->rssi);
        p += w; left -= w;
    }

    // Close the array and the object — without this the JSON is invalid,
    // r.json() throws in the browser, and the Discover card stays empty.
    if (left > 2) { snprintf(p, left, "]}"); }
    else { snprintf(buf, sizeof(buf), "{\"scanning\":false,\"results\":[]}"); }

    _server.sendHeader("Cache-Control", "no-store");
    _server.sendHeader("X-Content-Type-Options", "nosniff");
    _server.send(200, "application/json", buf);
}

// ──────────────────────────────────────────────────────────────────────────────
// OTA Firmware Update Endpoint
// ──────────────────────────────────────────────────────────────────────────────
// Correct ESP32 WebServer pattern: one UPLOAD callback streams the bytes,
// one RESPONSE callback sends the single final JSON. Never send() from
// inside UPLOAD_FILE_START/WRITE — it corrupts the upload connection.
//
// SECURITY STATUS (be honest): this endpoint has NO auth and NO signature
// check — anyone joined to the AP can flash firmware. Mitigations in place:
//   • size cap (rejects images larger than free sketch space),
//   • Update.abort() on any error (no wedged half-flash),
//   • single final response (no mid-upload sends).
// Full fix (admin session + ECDSA signature) is roadmap — see README.
// ──────────────────────────────────────────────────────────────────────────────

/// The upload runs inside handleClient() and blocks loop() for its whole
/// duration. Keep FC polling alive meanwhile so arming is still detected.
static void pumpFcDuringUpload() {
    fcStatusUpdate();
    MspMessage msg{};
    uint8_t budget = 128;
    while (budget-- > 0 && Serial1.available()) {
        if (mspParseByte((uint8_t)Serial1.read(), msg)) fcStatusFeed(msg);
    }
}

/// #12: reject images for the other chip or the full flasher image before a
/// single byte is written. Image header: magic 0xE9, chip id (u16 LE) at 12;
/// an application image carries esp_app_desc_t (magic 0xABCD5432) at 32.
static bool otaImageLooksRight(const uint8_t *buf, size_t len) {
    if (len >= 1 && buf[0] == 0xFF) {
        // The classic-ESP32 flasher image starts with 0x1000 bytes of padding.
        snprintf(_otaError, sizeof(_otaError),
                 "full flasher image: use the -update.bin file");
        return false;
    }
    if (len < 36 || buf[0] != 0xE9) {
        snprintf(_otaError, sizeof(_otaError), "not an ESP32 firmware file");
        return false;
    }
#if CONFIG_IDF_TARGET_ESP32C3
    const uint16_t wantChip = 0x0005;
    const char *wantName = "ESP32-C3";
#else
    const uint16_t wantChip = 0x0000;
    const char *wantName = "ESP32";
#endif
    uint16_t chip = (uint16_t)(buf[12] | (buf[13] << 8));
    if (chip != wantChip) {
        snprintf(_otaError, sizeof(_otaError),
                 "wrong file: this board needs the %s update file", wantName);
        return false;
    }
    uint32_t appMagic = (uint32_t)buf[32] | ((uint32_t)buf[33] << 8) |
                        ((uint32_t)buf[34] << 16) | ((uint32_t)buf[35] << 24);
    if (appMagic != 0xABCD5432UL) {
        snprintf(_otaError, sizeof(_otaError),
                 "full flasher image: use the -update.bin file");
        return false;
    }
    return true;
}

static void handleOtaUpload() {
    HTTPUpload& upload = _server.upload();

    if (upload.status == UPLOAD_FILE_START) {
        _otaActive = true;
        _otaOk = false;
        _otaError[0] = '\0';
        _otaBytes = 0;
        _otaMaxBytes = ESP.getFreeSketchSpace();
        DBG("OTA: start '%s'", upload.filename.c_str());
        if (fcIsArmed()) {
            // Flight safety: never flash (and reboot) an armed quad. The rest
            // of the upload is drained silently; the response reports this.
            snprintf(_otaError, sizeof(_otaError), "not allowed while FC is armed");
            _otaActive = false;
            return;
        }
        // Give the upload full radio: stop BLE scans, pause reconnects and
        // keep-alives until END/ABORT/response (see camera_manager quiet).
        camSetOtaQuiet(true);

        if (_otaMaxBytes == 0) {
            snprintf(_otaError, sizeof(_otaError), "no space for update");
            Update.abort();
            _otaActive = false;
            camSetOtaQuiet(false);
            return;
        }
        if (!Update.begin(UPDATE_SIZE_UNKNOWN)) {
            snprintf(_otaError, sizeof(_otaError), "Begin failed");
            DBG("OTA: begin error: %s", Update.errorString());
            Update.abort();
            _otaActive = false;
            camSetOtaQuiet(false);
        }
    } else if (upload.status == UPLOAD_FILE_WRITE) {
        if (!_otaActive) return;  // begin already failed — drain silently
        pumpFcDuringUpload();
        if (fcIsArmed()) {
            snprintf(_otaError, sizeof(_otaError), "FC armed during upload — aborted");
            Update.abort();
            _otaActive = false;
            camSetOtaQuiet(false);
            return;
        }
        if (_otaBytes == 0 && !otaImageLooksRight(upload.buf, upload.currentSize)) {
            Update.abort();
            _otaActive = false;
            camSetOtaQuiet(false);
            return;
        }
        // Incremental size cap: never write past free sketch space.
        if (_otaBytes + upload.currentSize > _otaMaxBytes) {
            snprintf(_otaError, sizeof(_otaError), "image too large");
            Update.abort();
            _otaActive = false;
            camSetOtaQuiet(false);
            return;
        }
        if (Update.write(upload.buf, upload.currentSize) != upload.currentSize) {
            snprintf(_otaError, sizeof(_otaError), "Write failed");
            DBG("OTA: write error: %s", Update.errorString());
            Update.abort();
            _otaActive = false;
            camSetOtaQuiet(false);
        } else {
            _otaBytes += upload.currentSize;
        }
    } else if (upload.status == UPLOAD_FILE_END) {
        if (_otaActive && Update.end(true)) {
            DBG("OTA: success, %u bytes written", (unsigned)upload.totalSize);
            _otaOk = true;
            // Keep quiet through the reboot in handleOtaResponse.
        } else {
            if (!_otaError[0]) snprintf(_otaError, sizeof(_otaError), "End failed");
            DBG("OTA: end error: %s", Update.errorString());
            Update.abort();
            _otaActive = false;
            camSetOtaQuiet(false);
        }
    } else if (upload.status == UPLOAD_FILE_ABORTED) {
        Update.abort();
        _otaActive = false;
        camSetOtaQuiet(false);
        snprintf(_otaError, sizeof(_otaError), "upload aborted");
    }
}

static void handleOtaResponse() {
    _server.sendHeader("Connection", "close");
    if (_otaOk) {
        _otaOk = false;
        _server.send(200, "application/json",
            "{\"ok\":true,\"message\":\"Firmware updated! Rebooting...\"}");
        scheduleDeferred(WEB_DEFER_REBOOT);   // P01: no delay() in the handler
    } else {
        char out[160];
        snprintf(out, sizeof(out), "{\"ok\":false,\"error\":\"%s\"}",
                 _otaError[0] ? _otaError : "update failed");
        _otaError[0] = '\0';
        camSetOtaQuiet(false);  // failed update: resume BLE activity
        _server.send(500, "application/json", out);
    }
}

static void handleOtaStatus() {
    char out[128];
    snprintf(out, sizeof(out), 
        "{\"ok\":true,\"version\":\"%s\",\"free_heap\":%lu}",
        FIRMWARE_VERSION, (unsigned long)ESP.getFreeHeap());
    _server.send(200, "application/json", out);
}

static void redirectToRoot() {
    String uri = _server.uri();
    // API paths must fail closed with JSON (not a 302 to HTML) so wrong-method
    // probes and scripts can't be hidden behind the captive-portal redirect.
    if (uri.startsWith("/api/")) {
        _server.send(404, "application/json",
                     "{\"ok\":false,\"error\":\"not found\"}");
        return;
    }
    _server.sendHeader(String("Location"), String("http://") + _ipStr + "/", true);
    _server.send(302, "text/plain", "");
}

