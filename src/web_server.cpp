// P01: AP restart / reboot are never executed inside a request handler (that
// needed delay() to flush the response and stalled loop()). The handler sends
// its reply and schedules the action; webUpdate() runs it once the deadline
// has passed, so the TCP stack had a few loop() ticks to flush.
enum WebDeferredAction : uint8_t { WEB_DEFER_NONE, WEB_DEFER_AP_RESTART, WEB_DEFER_REBOOT };
static WebDeferredAction _deferredAction = WEB_DEFER_NONE;
static uint32_t          _deferredAtMs   = 0;
static const uint32_t    kDeferredActionDelayMs = 300;

static void scheduleDeferred(WebDeferredAction action) {
    // A pending reboot always wins over an AP restart.
    if (_deferredAction == WEB_DEFER_REBOOT) return;
    _deferredAction = action;
    _deferredAtMs   = millis();
}

